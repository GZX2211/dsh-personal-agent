/**
 * 组件拿到的翻译函数：键受词典约束，语言每次渲染都取自 locale 服务。
 *
 * 带占位符的文案（如「线程 {count}」）用第二个参数填充；缺省值原样保留占位符，
 * 让漏传参数在界面上可见，而不是静默变成空白。
 */
export type Translate = (key: keyof Dict, params?: TranslateParams) => string

